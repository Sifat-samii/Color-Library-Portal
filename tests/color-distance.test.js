const assert = require("assert");
const { labFromHex, deltaE00 } = require("../server/color-distance");
const { ADOBE_RGB_TO_XYZ } = require("../public/adobe-rgb");

function close(actual, expected, tolerance = 0.0002) {
  assert.ok(Math.abs(actual - expected) <= tolerance, `${actual} is not within ${tolerance} of ${expected}`);
}

const white = labFromHex("#FFFFFF");
close(white[0], 100, 0.001);
close(white[1], 0, 0.001);
close(white[2], 0, 0.001);

// CSS Color 4 a98-rgb, from the Adobe RGB (1998) chromaticities (x, y) and D65.
const cssA98 = [
  [0.5766690429, 0.1855582379, 0.1882286462],
  [0.2973449753, 0.6273635663, 0.0752914585],
  [0.0270313614, 0.0706888525, 0.9913375368]
];
for (let row = 0; row < 3; row += 1) {
  for (let column = 0; column < 3; column += 1) close(ADOBE_RGB_TO_XYZ[row][column], cssA98[row][column], 0.000000001);
}

const red = labFromHex("#FF0000");
assert.ok(Math.abs(red[0] - 53.2329) > 5, "Adobe RGB red is not the sRGB Lab value");
assert.ok(red[0] > 60 && red[0] < 70);

const green = labFromHex("#00FF00");
assert.ok(Math.abs(green[0] - 87.737) > 2, "Adobe RGB green is not the sRGB Lab value");

const black = labFromHex("#000000");
close(black[0], 0, 0.001);
close(black[1], 0, 0.001);
close(black[2], 0, 0.001);

